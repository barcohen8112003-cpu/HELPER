// Anonymous public web, beside the Chromium windows. Obscura (Apache-2.0) is a small Rust browser with V8 and
// Chrome DevTools Protocol. It serves search, page text and price surveys. Webtop, Google Home, Gemini, the
// signed-in errand window and the remote desktop stay on their own ports and profiles; this module never opens them.
//
// The process listens on 127.0.0.1 only. A missing binary, a crash, a timeout, a private address or a block page
// returns empty, and the caller keeps the path it had before (plain fetch, Tavily/DuckDuckGo, Jina, Chromium).
import fs from 'node:fs'
import http from 'node:http'
import net from 'node:net'
import { spawn } from 'node:child_process'
import WebSocket from 'ws'
import { config } from './config.js'

// Chromium debug ports already used in this project. Obscura must not attach to any of them.
const RESERVED_PORTS = new Set([9222, 9223, 9224, 9226, 9227])
const BLOCKED = /just a moment|cf-browser-verification|attention required|access denied|unusual traffic|pardon our interruption|enable javascript and cookies|request blocked|the request could not be satisfied|generated by cloudfront|verify you are human|captcha/i
const PRODUCT = /מחיר|זול|השוו|השוואת|דגם|zap|price|cheap|compare|קנה|תקנה/i

let hooks = {}
let child = null
let stopping = false
let restartTimer = null
let rssTimer = null
let failures = 0
let downUntil = 0
let restartDelay = 1000
let chain = Promise.resolve()

export const _setForTest = (next) => {
  hooks = { ...hooks, ...next }
}
export const _resetForTest = () => {
  hooks = {}
  failures = 0
  downUntil = 0
}
export const _clearBreaker = () => {
  failures = 0
  downUntil = 0
}

export function safePort(port = config.obscura.port) {
  const n = Number(port) || 9228
  if (!Number.isInteger(n) || n < 1 || n > 65535 || RESERVED_PORTS.has(n)) return 9228
  return n
}

// Always loopback. There is no setting that publishes this port.
export function launchArgs({ port = config.obscura.port, heapMb = config.obscura.heapMb, proxy = config.obscura.proxy } = {}) {
  const args = ['--v8-flags', `--max-old-space-size=${heapMb}`]
  if (proxy) args.push('--proxy', proxy)
  args.push('serve', '--host', '127.0.0.1', '--port', String(safePort(port)), '--max-connections', '2', '--quiet')
  return args
}

export function pageBlocked(text) {
  return BLOCKED.test(String(text || ''))
}

function publicIp(ip) {
  if (net.isIP(ip) === 4) {
    const [a, b] = ip.split('.').map(Number)
    if (a === 0 || a === 10 || a === 127 || a >= 224) return false
    if (a === 100 && b >= 64 && b <= 127) return false
    if (a === 169 && b === 254) return false
    if (a === 172 && b >= 16 && b <= 31) return false
    if (a === 192 && (b === 168 || b === 0)) return false
    if (a === 198 && (b === 18 || b === 19)) return false
    return true
  }
  const s = ip.toLowerCase()
  if (s === '::' || s === '::1' || s.startsWith('fe80:') || s.startsWith('fc') || s.startsWith('fd') || s.startsWith('ff')) return false
  return true
}

function sessionHost(host) {
  try {
    const site = new URL(config.webtop.url).hostname.replace(/\.$/, '').toLowerCase()
    return Boolean(site) && (host === site || host.endsWith('.' + site))
  } catch {
    return false
  }
}

// Empty when the URL may be read anonymously. A signed-in site is refused here so it stays on its Chromium window.
export function publicUrlProblem(raw) {
  let u
  try {
    u = new URL(String(raw))
  } catch {
    return 'כתובת לא תקינה'
  }
  if (u.protocol !== 'http:' && u.protocol !== 'https:') return 'רק http/https'
  if (u.username || u.password) return 'כתובת עם סיסמה אסורה'
  const host = u.hostname.replace(/^\[|\]$/g, '').replace(/\.$/, '').toLowerCase()
  if (!host || host === 'localhost' || host.endsWith('.localhost') || host.endsWith('.local')) return 'כתובת פנימית חסומה'
  if (net.isIP(host)) return publicIp(host) ? '' : 'כתובת פנימית חסומה'
  if (!host.includes('.')) return 'שם מחשב בלי דומיין חסום'
  if (sessionHost(host)) return 'אתר מחובר נקרא מהחלון שלו'
  return ''
}

export function citeToUrl(cite) {
  const raw = String(cite || '').split('›')[0].split('>')[0].trim().replace(/\s+/g, '')
  if (!raw) return ''
  if (/^https?:\/\//i.test(raw)) return raw
  if (/^[\w.-]+\.[a-z]{2,}([/:?#]|$)/i.test(raw)) return 'https://' + raw
  return ''
}

export function pickResultUrl(cite, href) {
  const cited = citeToUrl(cite)
  const link = String(href || '')
  if (/^https?:\/\//i.test(link) && !/bing\.com\/ck\//i.test(link) && !/bing\.com\/aclick/i.test(link)) return link
  if (cited) return cited
  return /^https?:\/\//i.test(link) ? link : ''
}

export function parseSearchRows(raw) {
  const rows = Array.isArray(raw) ? raw : []
  const out = []
  for (const r of rows) {
    const title = String(r?.title || '').replace(/\s+/g, ' ').trim()
    const url = pickResultUrl(r?.cite, r?.url || r?.href)
    if (!title || !/^https?:\/\//i.test(url)) continue
    out.push({ title: title.slice(0, 180), url, snippet: String(r?.snippet || '').replace(/\s+/g, ' ').trim().slice(0, 300) })
    if (out.length >= 6) break
  }
  return out
}

export function moneyCap(budget) {
  const n = Number(String(budget ?? '').replace(/[^\d.]/g, ''))
  return Number.isFinite(n) && n > 0 ? n : 0
}

export function parseOffers(raw) {
  const rows = Array.isArray(raw) ? raw : Array.isArray(raw?.rows) ? raw.rows : []
  const out = []
  for (const r of rows) {
    const title = String(r?.title || '').replace(/\s+/g, ' ').trim()
    const price = Number(String(r?.price ?? '').replace(/,/g, '').replace(/[^\d.]/g, ''))
    if (!title || !Number.isFinite(price) || price <= 0) continue
    let link = String(r?.href || r?.link || '')
    try {
      link = link ? new URL(link, 'https://www.zap.co.il').href : ''
    } catch {
      link = ''
    }
    out.push({
      title: title.slice(0, 140),
      price,
      priceText: `${price.toLocaleString('en-US')} ₪`,
      shop: String(r?.shop || '').replace(/\s+/g, ' ').trim().slice(0, 80),
      link,
      used: /משומש|מחודש|refurbished|\bused\b/i.test(title),
    })
  }
  return out
}

export function rankOffers(rows, { budget, includeUsed = false } = {}) {
  const cap = moneyCap(budget)
  let list = (rows || []).filter((r) => includeUsed || !r.used)
  if (cap) list = list.filter((r) => r.price <= cap)
  return [...list].sort((a, b) => a.price - b.price)
}

export function formatSurvey(rows, query) {
  if (!rows?.length) return ''
  const line = (r, i) => `${i + 1}. ${r.title}: ${r.priceText}${r.shop ? ` · ${r.shop}` : ''}${r.link ? `\n${r.link}` : ''}`
  return [
    `זאפ, "${query}": ${rows.length} דגמים, הזול קודם. המחיר הוא «החל מ-» כפי שזאפ מציג; דמי משלוח רק אם השורה אומרת אותם. נקרא עם Obscura, בלי סל ובלי קופה.`,
    ...rows.slice(0, 8).map(line),
  ].join('\n')
}

function engineAllowed() {
  if (!config.obscura.enabled || hooks.forceOff) return false
  if (process.env.HELPER_OFFLINE === '1' && !hooks.base) return false
  if (Date.now() < downUntil) return false
  return true
}

export function obscuraInstalled() {
  if (!config.obscura.enabled) return false
  if (hooks.installed != null) return Boolean(hooks.installed)
  try {
    return fs.existsSync(config.obscura.bin)
  } catch {
    return false
  }
}

function noteOk() {
  failures = 0
  downUntil = 0
  restartDelay = 1000
}

function noteFailure(err) {
  const msg = String(err?.message || err)
  if (!/not obscura|ECONNREFUSED|ECONNRESET|socket hang up|socket closed|EPIPE|ETIMEDOUT|timeout|did not become ready/i.test(msg)) return
  failures++
  if (failures >= (/not obscura/i.test(msg) ? 1 : 3)) downUntil = Date.now() + 60_000
}

function baseUrl() {
  return String(hooks.base || `http://127.0.0.1:${safePort()}`).replace(/\/$/, '')
}

function wsUrl() {
  const u = new URL(baseUrl())
  u.protocol = 'ws:'
  u.pathname = '/devtools/browser'
  u.search = ''
  return u.href
}

function exclusive(fn) {
  const run = chain.then(fn, fn)
  chain = run.then(() => {}, () => {})
  return run
}

function childEnv() {
  const timeoutMs = config.obscura.timeoutMs
  return {
    PATH: process.env.PATH || '/usr/local/bin:/usr/bin:/bin',
    LANG: 'C.UTF-8',
    TZ: 'Asia/Jerusalem',
    OBSCURA_NAV_TIMEOUT_MS: String(timeoutMs),
    OBSCURA_SCRIPT_DEADLINE_MS: String(Math.min(timeoutMs, 12000)),
    OBSCURA_FETCH_TIMEOUT_MS: '12000',
    OBSCURA_CDP_COMMAND_TIMEOUT_MS: String(timeoutMs + 5000),
    OBSCURA_TIMEZONE: 'Asia/Jerusalem',
    OBSCURA_NETWORK_BODY_BUFFER_BYTES: '1048576',
    OBSCURA_NETWORK_BODY_BUFFER_ENTRIES: '32',
    RUST_LOG: 'warn',
  }
}

function getJson(url, timeoutMs = 1500) {
  return new Promise((resolve, reject) => {
    const req = http.get(url, { timeout: timeoutMs }, (res) => {
      const chunks = []
      res.on('data', (c) => chunks.push(c))
      res.on('end', () => {
        try {
          resolve(JSON.parse(Buffer.concat(chunks).toString('utf8')))
        } catch (e) {
          reject(e)
        }
      })
    })
    req.on('error', reject)
    req.on('timeout', () => req.destroy(new Error('timeout')))
  })
}

function rssMb(pid) {
  try {
    const status = fs.readFileSync(`/proc/${pid}/status`, 'utf8')
    const m = status.match(/VmRSS:\s+(\d+)\s+kB/)
    return m ? Number(m[1]) / 1024 : 0
  } catch {
    return 0
  }
}

// One page at a time. The socket is closed when the call ends, so a stuck page cannot pin a target.
function withPage(url, expression) {
  const timeoutMs = config.obscura.timeoutMs + 3000
  return exclusive(() => new Promise((resolve, reject) => {
    let settled = false
    let targetId = ''
    const pending = new Map()
    const finish = (err, value) => {
      if (settled) return
      settled = true
      clearTimeout(timer)
      for (const p of pending.values()) p.bad(new Error('socket closed'))
      pending.clear()
      try { ws.close() } catch {}
      err ? reject(err) : resolve(value)
    }
    const timer = setTimeout(() => finish(new Error('timeout')), timeoutMs)
    const ws = new WebSocket(wsUrl(), { handshakeTimeout: 3000, perMessageDeflate: false, maxPayload: 16 * 1024 * 1024 })
    let next = 0
    const send = (method, params = {}, sessionId) => new Promise((ok, bad) => {
      if (settled) return bad(new Error('socket closed'))
      const id = ++next
      const t = setTimeout(() => {
        pending.delete(id)
        bad(new Error(`timeout ${method}`))
      }, timeoutMs)
      pending.set(id, {
        ok: (v) => (clearTimeout(t), ok(v)),
        bad: (e) => (clearTimeout(t), bad(e)),
      })
      const frame = { id, method, params }
      if (sessionId) frame.sessionId = sessionId
      ws.send(JSON.stringify(frame))
    })
    ws.on('message', (data) => {
      let msg
      try { msg = JSON.parse(data.toString()) } catch { return }
      if (!msg.id || !pending.has(msg.id)) return
      const p = pending.get(msg.id)
      pending.delete(msg.id)
      if (msg.error) p.bad(new Error(msg.error.message || 'cdp'))
      else p.ok(msg.result || {})
    })
    ws.on('error', (e) => finish(e))
    ws.on('close', () => finish(new Error('socket closed')))
    ws.on('open', () => {
      ;(async () => {
        try {
          try {
            await send('LP.getMarkdown', {})
          } catch (e) {
            if (!/No page/i.test(e.message)) throw new Error('not obscura')
          }
          const created = await send('Target.createTarget', { url: 'about:blank' })
          targetId = created.targetId
          if (!targetId) throw new Error('not obscura')
          const attached = await send('Target.attachToTarget', { targetId, flatten: true })
          if (!attached.sessionId) throw new Error('not obscura')
          await send('Page.navigate', { url }, attached.sessionId)
          const ev = await send('Runtime.evaluate', { expression, returnByValue: true }, attached.sessionId)
          if (ev.exceptionDetails) throw new Error('eval failed')
          const value = ev.result?.value
          await send('Target.closeTarget', { targetId }).catch(() => {})
          targetId = ''
          finish(null, value)
        } catch (e) {
          if (targetId) await send('Target.closeTarget', { targetId }).catch(() => {})
          finish(e)
        }
      })()
    })
  }))
}

function asJson(value) {
  if (typeof value !== 'string') return value
  return JSON.parse(value)
}

const BING_EXPR = `(() => {
  const clean = (s) => (s || '').replace(/\\s+/g, ' ').trim()
  const rows = [...document.querySelectorAll('li.b_algo')].slice(0, 8).map((li) => {
    const a = li.querySelector('h2 a')
    const cite = li.querySelector('cite')
    const p = li.querySelector('.b_caption p, p')
    return { title: clean(a && a.innerText), url: (a && a.href) || '', cite: clean(cite && cite.innerText), snippet: clean(p && p.innerText).slice(0, 300) }
  })
  const text = (document.body && document.body.innerText || '').slice(0, 400)
  return JSON.stringify({ text, rows })
})()`

const ZAP_EXPR = `(() => {
  const text = (document.body && document.body.innerText || '').slice(0, 1500)
  const rows = [...document.querySelectorAll('.model-row-v2')].slice(0, 8).map((row) => {
    const a = row.querySelector('.card-v2__title a')
    const amount = row.querySelector('.card-v2__price-amount')
    const stores = row.querySelector('.card-v2__stores-link')
    return {
      title: (a && a.innerText || '').replace(/\\s+/g, ' ').trim(),
      price: amount && amount.innerText,
      href: a && a.getAttribute('href'),
      shop: (stores && stores.innerText || '').replace(/\\s+/g, ' ').trim(),
    }
  })
  return JSON.stringify({ text, rows })
})()`

const YT_EXPR = `(() => {
  const out = []
  const seen = new Set()
  for (const a of document.querySelectorAll('a[href*="watch?v="]')) {
    const m = String(a.href || '').match(/[?&]v=([\\w-]{11})/)
    if (!m || seen.has(m[1])) continue
    const title = (a.innerText || a.getAttribute('title') || '').replace(/\\s+/g, ' ').trim()
    if (title.length < 2) continue
    seen.add(m[1])
    out.push({ id: m[1], title: title.slice(0, 140) })
    if (out.length >= 8) break
  }
  return JSON.stringify(out)
})()`

function pageExpr(max) {
  const n = Math.min(30000, Math.max(500, Number(max) || 12000))
  return `(() => JSON.stringify({ title: document.title || '', href: location.href, text: ((document.body && document.body.innerText) || '').slice(0, ${n}) }))()`
}

async function evalPage(url, expression) {
  const problem = publicUrlProblem(url)
  if (problem) {
    const err = new Error(problem)
    err.refused = true
    throw err
  }
  return withPage(url, expression)
}

function logFail(what, err) {
  if (err?.refused) return
  noteFailure(err)
  console.log(`[obscura] ${what} לא הצליח (${String(err?.message || err).slice(0, 160)}); ממשיך בדרך הרגילה`)
}

// Page text, or '' when Obscura should not be used. Never throws for a site failure.
export async function readPublicPage(url, { maxChars = 12000 } = {}) {
  if (!engineAllowed()) return ''
  if (publicUrlProblem(url)) return ''
  const max = Math.min(30000, Math.max(500, Number(maxChars) || 12000))
  try {
    const data = asJson(await evalPage(url, pageExpr(max)))
    const text = String(data?.text || '').trim()
    if (!text || pageBlocked(text)) {
      if (text && pageBlocked(text)) console.log('[obscura] הדף נחסם; ממשיך בדרך הרגילה')
      return ''
    }
    noteOk()
    return text.slice(0, max)
  } catch (e) {
    logFail('קריאת דף', e)
    return ''
  }
}

export async function searchPublic(query) {
  if (!engineAllowed()) return null
  const q = String(query || '').trim()
  if (!q) return null
  const url = `https://www.bing.com/search?q=${encodeURIComponent(q)}&setlang=he&cc=il&count=8`
  try {
    const data = asJson(await evalPage(url, BING_EXPR))
    if (pageBlocked(data?.text) && !(data?.rows || []).length) {
      console.log('[obscura] החיפוש נחסם; ממשיך בדרך הרגילה')
      return null
    }
    const rows = parseSearchRows(data?.rows)
    if (!rows.length) return null
    noteOk()
    return rows
  } catch (e) {
    logFail('חיפוש', e)
    return null
  }
}

// Zap "from" prices. '' means the caller should use the previous survey (the signed-in window).
export async function surveyPrices(query, { budget, includeUsed = false } = {}) {
  if (!engineAllowed()) return ''
  const q = String(query || '').trim()
  if (!q) return ''
  const url = `https://www.zap.co.il/search.aspx?keyword=${encodeURIComponent(q)}`
  try {
    const data = asJson(await evalPage(url, ZAP_EXPR))
    if (pageBlocked(data?.text)) {
      console.log('[obscura] זאפ חסם את הסקר; ממשיך בדרך הרגילה')
      return ''
    }
    const ranked = rankOffers(parseOffers(data), { budget, includeUsed })
    if (ranked.length < 2) return ''
    noteOk()
    return formatSurvey(ranked, q)
  } catch (e) {
    logFail('סקר מחירים', e)
    return ''
  }
}

// YouTube results page, only as a last resort when the API and the plain HTML parse found nothing.
export async function youtubePublic(query, max = 5) {
  if (!engineAllowed()) return []
  const q = String(query || '').trim()
  if (!q) return []
  const url = `https://www.youtube.com/results?search_query=${encodeURIComponent(q)}&hl=he`
  try {
    const rows = asJson(await evalPage(url, YT_EXPR))
    const list = (Array.isArray(rows) ? rows : [])
      .filter((v) => v?.id && v?.title)
      .slice(0, Math.max(1, Math.min(10, max)))
      .map((v) => ({ id: String(v.id), title: String(v.title), channel: '', published: '' }))
    if (list.length) noteOk()
    return list
  } catch (e) {
    logFail('יוטיוב', e)
    return []
  }
}

// Facts gathered before an order. The signed-in window still does the cart and the checkout.
export async function researchNotes(goal) {
  if (!engineAllowed()) return ''
  const q = String(goal || '').trim().slice(0, 300)
  if (!q) return ''
  const bits = []
  const found = await searchPublic(q)
  if (found?.length) bits.push('Search:', ...found.slice(0, 3).map((r) => `- ${r.title} ${r.url}`))
  if (PRODUCT.test(q)) {
    const prices = await surveyPrices(q)
    if (prices) bits.push(prices.split('\n').slice(0, 8).join('\n'))
  }
  if (!bits.length) return ''
  return [
    'Public pages were already read in the anonymous browser. Use these facts. This signed-in window is for the shop session, cart and checkout. Do not repeat the public survey here unless the notes are empty or a shop page contradicts them.',
    ...bits,
  ].join('\n').slice(0, 1800)
}

async function waitReady(timeoutMs) {
  const deadline = Date.now() + timeoutMs
  const url = `${baseUrl()}/json/version`
  while (Date.now() < deadline) {
    if (stopping) return false
    try {
      const info = await getJson(url, 1000)
      if (String(info?.webSocketDebuggerUrl || '').includes('/devtools/browser')) return true
    } catch {}
    await new Promise((r) => setTimeout(r, 200))
  }
  return false
}

function scheduleRestart() {
  if (stopping) return
  clearTimeout(restartTimer)
  const wait = restartDelay
  restartDelay = Math.min(30_000, restartDelay * 2)
  restartTimer = setTimeout(() => {
    restartTimer = null
    spawnServer()
  }, wait)
  restartTimer.unref?.()
}

function spawnServer() {
  if (stopping || !config.obscura.enabled) return
  if (!fs.existsSync(config.obscura.bin)) return
  const args = launchArgs()
  child = spawn(config.obscura.bin, args, { stdio: ['ignore', 'pipe', 'pipe'], env: childEnv(), windowsHide: true })
  child.stdout.on('data', () => {})
  child.stderr.on('data', () => {})
  child.on('error', (e) => {
    console.log(`[obscura] לא עלה (${e.message}); ממשיך בדרך הרגילה`)
    child = null
  })
  child.on('exit', () => {
    child = null
    if (!stopping) scheduleRestart()
  })
  clearInterval(rssTimer)
  rssTimer = setInterval(() => {
    if (!child?.pid) return
    const rss = rssMb(child.pid)
    if (rss > config.obscura.maxRssMb) {
      console.log(`[obscura] ${Math.round(rss)}MB, מעל ${config.obscura.maxRssMb}MB; מאתחל`)
      child.kill('SIGTERM')
    }
  }, 30_000)
  rssTimer.unref?.()
}

// Starts the loopback server when the binary is there. Does not throw. HELPER_OFFLINE skips it (tests).
export async function startObscura() {
  stopping = false
  if (!config.obscura.enabled) return { started: false, reason: 'off' }
  if (process.env.HELPER_OFFLINE === '1') return { started: false, reason: 'offline' }
  if (!fs.existsSync(config.obscura.bin)) return { started: false, reason: 'missing' }
  spawnServer()
  const port = safePort()
  const ready = await waitReady(15_000)
  if (!ready) {
    noteFailure(new Error('did not become ready'))
    return { started: false, reason: 'not-ready', port }
  }
  noteOk()
  return { started: true, port }
}

export function stopObscura() {
  stopping = true
  clearTimeout(restartTimer)
  clearInterval(rssTimer)
  restartTimer = null
  rssTimer = null
  if (child && child.exitCode == null && !child.killed) {
    child.kill('SIGTERM')
    const stuck = child
    setTimeout(() => {
      if (stuck.exitCode == null) stuck.kill('SIGKILL')
    }, 2000).unref?.()
  }
}
